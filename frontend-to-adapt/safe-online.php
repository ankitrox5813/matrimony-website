    <h2>Safety Tips</h2>
    <ul>
      <li>Never share OTPs, passwords, banking credentials, or confidential verification codes with anyone.</li>
      <li>Avoid users who request money, gifts, investments, or financial assistance.</li>
      <li>Verify identity carefully before sharing personal information or arranging meetings.</li>
      <li>Report suspicious behavior, fake profiles, harassment, or abuse immediately.</li>
      <li>Always meet in public places during initial meetings.</li>
      <li>Inform trusted family members or friends before meeting someone in person.</li>
      <li>Avoid rushing into emotional or financial commitments.</li>
      <li>Be cautious while sharing personal documents or sensitive information.</li>
    </ul>

    <div class="warning-box">
      <strong>Important:</strong> Aurivah will never ask for your banking password, OTP, debit card PIN, or confidential financial credentials.
    </div>

    <h2>Common Red Flags</h2>
    <p>Users should remain alert for suspicious behavior patterns that may indicate scams or fraudulent intent.</p>
    <ul>
      <li>Requests for money, loans, gifts, or urgent financial help</li>
      <li>Emotional manipulation or pressure tactics</li>
      <li>Refusal to verify identity or participate in verification processes</li>
      <li>Profiles that appear unrealistically perfect or too-good-to-be-true</li>
      <li>Inconsistent personal information or suspicious communication patterns</li>
      <li>Attempts to move conversations immediately outside the platform</li>
      <li>Aggressive, abusive, or threatening communication</li>
    </ul>

